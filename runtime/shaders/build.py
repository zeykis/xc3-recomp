#!/usr/bin/env python3
# Compiles the present-pass shaders (*.vert / *.frag here) to SPIR-V and writes runtime/src/present_spv.h.
# Needs glslangValidator (Vulkan SDK, or apt install glslang-tools). The header is committed: building the runtime
# does not need this script.
import os, struct, subprocess, sys, tempfile
here = os.path.dirname(os.path.abspath(__file__))
out = os.path.join(here, '..', 'src', 'present_spv.h')
lines = ['// generated by runtime/shaders/build.py from runtime/shaders/*.vert|frag (glslangValidator -V): do not edit',
         '#pragma once', '#include <stdint.h>']
for name in ['fullscreen.vert', 'blit.frag', 'easu.frag', 'rcas.frag', 'fg_luma.frag', 'fg_down.frag', 'fg_flow.frag', 'fg_interp.frag']:
    with tempfile.TemporaryDirectory() as td:
        spv = os.path.join(td, 'o.spv')
        subprocess.run(['glslangValidator', '-V', '-o', spv, os.path.join(here, name)], check=True)
        data = open(spv, 'rb').read()
    words = struct.unpack('<%dI' % (len(data) // 4), data)
    lines.append('static const uint32_t k_spv_%s[] = {' % name.replace('.', '_'))
    for i in range(0, len(words), 12):
        lines.append('    ' + ' '.join('0x%08x,' % w for w in words[i:i + 12]))
    lines.append('};')
open(out, 'w', newline='\n').write('\n'.join(lines) + '\n')
print('wrote', os.path.normpath(out))
